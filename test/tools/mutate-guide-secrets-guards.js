// Break each rule behind what agents say about the connector secrets file, in
// turn, and report which tests notice.
//
// Every agent is told that .rundock/mcp-secrets.json is kept out of git
// because setup adds .rundock/ to .gitignore, and that a synced folder copies
// it to every device the folder syncs to. ARCHITECTURE.md says the same to
// contributors. Each half of that is a small piece of text, or one line of
// setup, that can be lost with the prompt still reading well, which is why
// each is broken on purpose here and a test must go red for it.
//
// A guard whose mutation turns nothing red is reported as a FAILURE rather
// than passed over. An experiment that changes nothing has not been run.
//
//   node test/tools/mutate-guide-secrets-guards.js            # report
//   node test/tools/mutate-guide-secrets-guards.js --markdown # the same, as a table
//
// The files are restored afterwards, including when a run throws. The harness
// is the same shape as its siblings, deliberately a separate copy: pulling
// them together means editing instruments already in the gate.

